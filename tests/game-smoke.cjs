'use strict';
const { _electron: electron } = require('playwright-core');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const assert = require('node:assert/strict');

(async () => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'polycraft-game-'));
  let application;
  try {
    application = await electron.launch({
      ...(process.env.POLYCRAFT_EXECUTABLE ? { executablePath: process.env.POLYCRAFT_EXECUTABLE, args: [] } : { args: ['.'] }),
      env: { ...process.env, POLYCRAFT_TEST_DATA: directory }, timeout: 90000
    });
    const page = await application.firstWindow();
    const errors = [];
    const requests = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', request => requests.push(request.url()));
    page.on('console', message => { if (message.type() === 'error') console.log('Renderer:', message.text().slice(0, 500)); });
    await page.waitForFunction(() => document.querySelector('.brand img').naturalWidth > 0 && document.querySelector('#welcome .polycraft-label'));
    assert.equal(await page.locator('#cheats').isHidden(), true);
    await page.locator('#new-name').pressSequentially('moreamberplease');
    assert.equal(await page.locator('#cheat-dialog').evaluate(dialog => dialog.open), false);
    fs.mkdirSync('test-results', { recursive: true });
    await page.screenshot({ path: 'test-results/launcher.png' });
    await page.locator('#new-name').fill('Acceptance island');
    await Promise.all([page.waitForEvent('domcontentloaded', { timeout: 90000 }), page.locator('#new-game button').click({ noWaitAfter: true })]);
    await page.waitForTimeout(8000);
    console.log('Loading:', await page.evaluate(() => ({ status: document.getElementById('status').textContent, state: window.PolycraftControls.manager()?.activeGameState?.name, hasLoadedLevel: window.PolycraftControls.manager()?.hasLoadedLevel, polycraft: !!window.polycraft })));
    fs.mkdirSync('test-results', { recursive: true });
    await page.screenshot({ path: 'test-results/game-loading.png' });
    await page.waitForFunction(() => window.polycraft?.controls.ready() || document.getElementById('error-dialog').open, null, { timeout: 60000 });
    assert.equal(await page.locator('#error-dialog').evaluate(dialog => dialog.open), false, await page.locator('#error-text').textContent());
    console.log('Game state:', await page.evaluate(() => window.polycraft.controls.manager().activeGameState.name));
    fs.mkdirSync('test-results', { recursive: true });
    await page.screenshot({ path: 'test-results/game-start.png' });
    const canvas = page.locator('#turbulenz_game_engine_canvas');
    const playPoint = await page.evaluate(() => Array.from(window.polycraft.controls.app.globals.guiRenderer.getv2RenderLocation(-220, -70)));
    const bounds = await canvas.boundingBox();
    await canvas.focus();
    await page.mouse.move(10, 10);
    await page.mouse.move(bounds.x + playPoint[0], bounds.y + playPoint[1], { steps: 5 });
    await page.waitForFunction(() => window.polycraft.controls.manager().activeGameState.readyToPlay);
    await page.mouse.click(bounds.x + playPoint[0], bounds.y + playPoint[1]);
    await page.waitForFunction(() => window.polycraft.controls.manager().activeGameState.name !== 'GamestateStartScreen');
    await page.waitForTimeout(2000);
    console.log('After Play:', await page.evaluate(() => window.polycraft.controls.manager().activeGameState.name));
    assert.equal(await page.evaluate(() => window.polycraft.controls.cheatsEnabled()), false);
    assert.equal(await page.evaluate(() => window.polycraft.slot().state.cheats.everEnabled), false);
    const shopPoint = await page.evaluate(() => Array.from(window.polycraft.controls.app.globals.guiRenderer.getv2RenderLocation(85, 113, 'topLeft')));
    await page.mouse.move(bounds.x + shopPoint[0], bounds.y + shopPoint[1]);
    await page.waitForTimeout(250);
    await page.mouse.click(bounds.x + shopPoint[0], bounds.y + shopPoint[1], { delay: 100 });
    await page.waitForFunction(() => window.polycraft.controls.manager().activeGameState.name === 'GamestateShop');
    assert.equal(await page.evaluate(() => {
      const shop = window.polycraft.controls.manager().activeGameState;
      if (shop.panelName !== 'resource') return false;
      shop.setButtonPanal('amber');
      return shop.panelName === 'resource';
    }), true);
    const closeShop = async () => {
      const point = await page.evaluate(() => Array.from(window.polycraft.controls.app.globals.guiRenderer.getv2RenderLocation(-100, 100, 'topRight')));
      await page.mouse.move(bounds.x + point[0], bounds.y + point[1]);
      await page.waitForTimeout(250);
      await page.mouse.click(bounds.x + point[0], bounds.y + point[1], { delay: 100 });
      await page.waitForFunction(() => window.polycraft.controls.manager().activeGameState.name === 'GamestatePlaying');
    };
    await page.screenshot({ path: 'test-results/craft-resources-locked.png' });
    await closeShop();
    await page.mouse.move(bounds.x + shopPoint[0], bounds.y + shopPoint[1]);
    await page.waitForTimeout(250);
    await page.mouse.click(bounds.x + shopPoint[0], bounds.y + shopPoint[1], { delay: 100 });
    await page.waitForFunction(() => window.polycraft.controls.manager().activeGameState.name === 'GamestateShop');
    await page.locator('#turbulenz_game_engine_canvas').focus();
    await page.keyboard.type('moreamberplease');
    await page.locator('#cheat-dialog').waitFor({ state: 'visible' });
    assert.equal(await page.locator('#cheats-enabled').isChecked(), true);
    assert.equal(await page.locator('#cheats').isVisible(), true);
    await page.locator('#cheats-enabled').uncheck();
    await page.waitForFunction(() => !window.polycraft.slot().state.cheats.enabled && document.getElementById('status').textContent.startsWith('Saved locally'));
    assert.equal(await page.locator('#cheat-tools').evaluate(fieldset => fieldset.disabled), true);
    assert.equal(await page.evaluate(() => window.polycraft.slot().state.cheats.everEnabled), true);
    assert.equal(await page.locator('#cheats').isHidden(), true);
    assert.equal(await page.evaluate(() => window.polycraft.controls.cheatsEnabled()), false);
    await page.locator('#cheats-enabled').check();
    await page.waitForFunction(() => window.polycraft.slot().state.cheats.enabled && document.getElementById('status').textContent.startsWith('Saved locally'));
    assert.equal(await page.evaluate(() => window.polycraft.controls.paused), true);
    await page.evaluate(() => { window.polycraft.controls.manager().getHero().getEC('ECHealth').health = 1; });
    await page.locator('#heal').click();
    assert.equal(await page.evaluate(() => { const health = window.polycraft.controls.manager().getHero().getEC('ECHealth'); return health.getHealth() === health.getMaxHealth(); }), true);
    await page.locator('#amber').fill('1234');
    await page.locator('#wood').fill('0');
    await page.locator('#stone').fill('0');
    await page.locator('#resource-form button').click();
    assert.equal(await page.evaluate(() => window.polycraft.controls.amounts().amber), 1234);
    await page.locator('#fill').click();
    assert.equal(await page.evaluate(() => { const a = window.polycraft.controls.amounts(); return a.wood === a.woodCap && a.stone === a.stoneCap; }), true);
    await page.locator('#invincible').check();
    await page.locator('#instant-build').check();
    await page.screenshot({ path: 'test-results/cheats.png' });
    await page.locator('#close-cheats').click();
    await page.waitForFunction(() => !window.polycraft.controls.paused);
    await closeShop();
    console.log('PASS: Craft Resource X closes with cheats disabled and enabled');
    await page.locator('#cheats').click();
    await page.locator('#cheat-dialog').waitFor({ state: 'visible' });
    await page.locator('#close-cheats').click();
    await page.waitForTimeout(500);
    const mechanics = await page.evaluate(() => {
      const controls = window.polycraft.controls;
      const game = controls.manager();
      const health = game.getHero().getEC('ECHealth');
      health.update();
      const before = health.getHealth();
      health.takeDamage(1, null, null, false, false);
      const heroProtected = health.godMode && before === health.getHealth();
      const entity = game.getEntityFactory().createInactiveEntityInstance('acceptance-scaffold', 'a_b_scaffold', game.getHero().getv3Location(), 0);
      const scaffold = entity.getEC('ECScaffold');
      scaffold.startedBuilding = true;
      scaffold.buildTime = 60;
      scaffold.minBuildSpeed = 1;
      controls.app.globals.desktopCheats.instantBuild = false;
      scaffold.updateBuildCompleteFraction(1);
      const normalFraction = scaffold.getBuildCompleteFraction();
      controls.app.globals.desktopCheats.instantBuild = true;
      scaffold.updateBuildCompleteFraction(1);
      const instantFraction = scaffold.getBuildCompleteFraction();
      return { heroProtected, normalFraction, instantFraction };
    });
    assert.equal(mechanics.heroProtected, true);
    assert.ok(mechanics.normalFraction > 0 && mechanics.normalFraction < 1);
    assert.equal(mechanics.instantFraction, 1);
    await page.evaluate(() => {
      window.polycraft.controls.pause(true);
      window.polycraft.controls.app.globals.gamePurchaseManager.purchaseItem('amberpack500Chunk');
    });
    await page.waitForFunction(() => window.polycraft.controls.amounts().amber === 1734);
    await page.evaluate(() => window.polycraft.checkpoint());
    await page.evaluate(() => window.polycraft.controls.app.globals.gamePurchaseManager.purchaseItem('amberpack500Chunk'));
    await page.waitForFunction(() => window.polycraft.controls.amounts().amber === 2234);
    await page.evaluate(() => window.polycraft.checkpoint());
    await page.evaluate(() => window.polycraft.controls.app.globals.gamePurchaseManager.purchaseItem('amberCrown'));
    await page.waitForFunction(() => window.polycraft.controls.app.globals.gamePurchaseManager.getOwned('amber-crown'));
    await page.evaluate(() => window.polycraft.checkpoint());
    await page.evaluate(() => window.polycraft.controls.app.globals.gamePurchaseManager.purchaseItem('amberWellOwned'));
    await page.waitForFunction(() => window.polycraft.controls.app.globals.gamePurchaseManager.getOwned('amber-well-owned'));
    const changedEntity = await page.evaluate(() => {
      const entity = window.polycraft.controls.manager().getGameSpaceList().flatMap(space => space.getEntitiesWithEC('ECResourceDispenser'))[0];
      entity.getEC('ECResourceDispenser').growFactor = 0.25;
      return { name: entity.name };
    });
    await page.evaluate(() => window.polycraft.checkpoint());
    const saved = await page.evaluate(() => ({ id: window.polycraft.slot().id, amounts: window.polycraft.controls.amounts(), data: window.polycraft.slot().state }));
    assert.ok(saved.data.userData.AdventureIncGameState);
    assert.ok(saved.data.userData.heroUpgrades);
    assert.equal(saved.data.cheats.invincible, true);
    assert.equal(saved.data.cheats.instantBuild, true);
    assert.equal(saved.data.cheats.everEnabled, true);
    assert.equal(saved.data.userItems.amber.amount, 0);
    assert.equal(saved.data.userItems['amber-crown'].amount, 1);
    assert.equal(saved.data.userItems['amber-well-owned'].amount, 1);
    console.log('PASS: original Play, cheat controls and coordinated world checkpoint');
    await page.locator('#slots').click();
    assert.match(await page.locator('.save').filter({ hasText: 'Acceptance island' }).textContent(), /Cheats used/);
    await page.locator('#save-list button', { hasText: 'Resume' }).click();
    assert.equal(await page.locator('#launcher').isHidden(), true);
    await page.evaluate(() => sessionStorage.setItem('polycraft-slot', window.polycraft.slot().id));
    await page.reload();
    await page.waitForFunction(() => window.polycraft?.controls.ready(), null, { timeout: 60000 });
    assert.equal(await page.evaluate(() => window.polycraft.controls.amounts().amber), saved.amounts.amber);
    assert.equal(await page.evaluate(() => window.polycraft.bridge.state.cheats.invincible), true);
    assert.equal(await page.locator('#cheats').isVisible(), true);
    assert.equal(await page.evaluate(() => window.polycraft.controls.app.globals.gamePurchaseManager.getOwned('amber-crown')), true);
    const growth = await page.evaluate(name => window.polycraft.controls.manager().getGameEntityByName(name).getEC('ECResourceDispenser').growFactor, changedEntity.name);
    assert.ok(growth >= 0.25 && growth < 0.4, 'Depleted resource state survives reload, allowing normal offline regrowth.');
    await page.evaluate(() => { const c = window.polycraft.controls; const a = c.amounts(); c.setAmounts(4321, a.wood, a.stone); });
    await page.waitForFunction(() => window.polycraft.slot().state.userData.softCurrency === '4321', null, { timeout: 40000 });
    console.log('PASS: 30-second autosave reaches the committed slot');
    const firstId = await page.evaluate(() => window.polycraft.slot().id);
    await page.locator('#slots').click();
    await page.locator('#new-name').fill('Second island');
    await page.locator('#new-game button').click({ noWaitAfter: true });
    await page.waitForFunction(id => window.polycraft?.slot().id !== id && window.polycraft?.controls.ready(), firstId, { timeout: 60000 });
    assert.equal(await page.evaluate(() => window.polycraft.controls.amounts().amber), 0);
    assert.equal(await page.evaluate(() => window.polycraft.bridge.state.cheats.invincible), false);
    await page.locator('#slots').click();
    assert.match(await page.locator('.save').filter({ hasText: 'Second island' }).textContent(), /Clean/);
    await page.locator('.save').filter({ hasText: 'Acceptance island' }).getByRole('button', { name: 'Continue', exact: true }).click({ noWaitAfter: true });
    await page.waitForFunction(id => window.polycraft?.slot().id === id && window.polycraft?.controls.ready(), firstId, { timeout: 60000 });
    assert.equal(await page.evaluate(() => window.polycraft.controls.amounts().amber), 4321);
    console.log('PASS: switching named islands keeps progress independent');
    assert.deepEqual(requests.filter(url => /^https?:/.test(url)), []);
    assert.deepEqual(errors, []);
    console.log('PASS: reload restores progress and cheats without external requests');
  } catch (error) {
    if (application) {
      const page = await application.firstWindow();
      await page.screenshot({ path: 'test-results/game-failure.png' });
      console.log('Failure state:', await page.evaluate(() => ({ state: window.polycraft?.controls.manager()?.activeGameState?.name, paused: window.polycraft?.controls.paused, status: document.getElementById('status').textContent, focus: document.activeElement?.id })));
    }
    throw error;
  } finally {
    if (application) await application.evaluate(({ app }) => app.exit());
    console.log('Test data:', directory);
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
